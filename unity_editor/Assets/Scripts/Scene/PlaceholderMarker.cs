using UnityEngine;

namespace Neram.Unity
{
    /// <summary>
    /// Marks generated placeholder geometry. The binder disables a placeholder as soon as a CAD object with the
    /// same role name (without "_PLACEHOLDER") exists under NERAM_Assembly.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class PlaceholderMarker : MonoBehaviour
    {
        [Tooltip("Role name of the CAD object that replaces this placeholder, e.g. Left_Hand_Module.")]
        public string role;
        [TextArea] public string note = "PLACEHOLDER geometry generated by NERAM setup. Replace with Neharikaa's FBX (same name, without _PLACEHOLDER).";
    }
}
