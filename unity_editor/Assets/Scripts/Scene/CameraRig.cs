using System.Collections.Generic;
using Neram.Core;
using UnityEngine;

namespace Neram.Unity
{
    /// <summary>
    /// Camera with two modes.
    ///  - Inspect (default): orbit around a pivot with smooth transitions between presets (Overview, Patient top, Feet &amp;
    ///    soles, Left/Right hand, Wearable, Chest/torso, Bedside controller, Theatre) and a focus target for the selected
    ///    region. Left-drag orbit, right/middle-drag pan, wheel zoom, Reset View.
    ///  - Free Roam: first-person movement through the whole theatre (WASD, mouse look, Space/Ctrl up/down, Shift faster).
    /// Both modes keep the camera inside the room and outside keep-out volumes (patient + table, equipment) using
    /// NavBounds (unit-tested). Input is supplied by NeramInputController.
    ///
    /// Composition: the dashboard panels cover the screen edges, so the rig shifts the projection centre (lens shift via
    /// the projection matrix) to the centre of the free "stage" rectangle reported by NeramApp. ScreenPointToRay and
    /// WorldToScreenPoint use the same matrix, so picking stays aligned.
    /// </summary>
    public sealed class CameraRig : MonoBehaviour
    {
        public Camera cam;
        public float smoothTime = 0.35f;
        public float minDistance = 0.2f;
        public float maxDistance = 9f;
        public float orbitSpeed = 0.25f;
        public float panSpeed = 0.0015f;
        public float zoomSpeed = 0.12f;
        [Header("Free Roam")]
        public float roamSpeed = 1.4f;
        public float roamFastMultiplier = 3f;
        public float lookSensitivity = 0.12f;
        public float collisionRadius = 0.18f;
        [Tooltip("Shift the projection centre to the free stage rectangle between the dashboard panels.")]
        public bool composeToStage = true;

        private Vector3 _pivot, _pivotVel;
        private float _yaw, _pitch, _dist;
        private float _tYaw, _tPitch, _tDist;
        private Vector3 _tPivot;
        private float _yawVel, _pitchVel, _distVel;
        private readonly List<CameraPreset> _presets = new List<CameraPreset>();
        private Rect _stagePx;
        private bool _hasStage;
        private Vector2 _shift, _shiftVel;

        private bool _roam;
        private Vector3 _roamPos;
        private float _roamYaw, _roamPitch;
        private NavBounds.Box _room;
        private bool _hasRoom;
        private NavBounds.Box[] _keepOut = new NavBounds.Box[0];

        public IReadOnlyList<CameraPreset> Presets => _presets;
        public bool FreeRoam => _roam;
        public event System.Action<bool> FreeRoamChanged;

        private void Awake()
        {
            if (cam == null) cam = GetComponentInChildren<Camera>();
            if (cam == null) cam = Camera.main;
            _presets.Clear();
            _presets.AddRange(FindObjectsByType<CameraPreset>(FindObjectsInactive.Include, FindObjectsSortMode.None));
            _presets.Sort((a, b) => a.order.CompareTo(b.order));
            CollectNavigation();
            ResetView(true);
        }

        /// <summary>Read the navigation volumes generated by setup (Nav_Room, Nav_KeepOut_*).</summary>
        public void CollectNavigation()
        {
            var keep = new List<NavBounds.Box>();
            _hasRoom = false;
            foreach (var v in FindObjectsByType<NeramNavVolume>(FindObjectsInactive.Exclude, FindObjectsSortMode.None))
            {
                var p = v.transform.position;
                var b = new NavBounds.Box(p.x, p.y, p.z, v.halfExtents.x, v.halfExtents.y, v.halfExtents.z);
                if (v.isRoom) { _room = b; _hasRoom = true; }
                else keep.Add(b);
            }
            if (!_hasRoom) { _room = new NavBounds.Box(0, 0.65, -0.35, 3.35, 1.45, 3.6); _hasRoom = true; }
            _keepOut = keep.ToArray();
        }

        public void ResetView(bool instant = false)
        {
            if (_roam) SetFreeRoam(false);
            if (_presets.Count > 0) GoTo(_presets[0], instant);
            else Set(Vector3.zero, -24, 27, 2.8f, instant);
        }

        public void GoTo(CameraPreset p, bool instant = false)
        {
            if (_roam) SetFreeRoam(false);
            Set(p.transform.position, p.yaw, p.pitch, p.distance, instant);
        }

        public void Set(Vector3 pivot, float yaw, float pitch, float distance, bool instant = false)
        {
            _tPivot = pivot; _tYaw = yaw; _tPitch = Mathf.Clamp(pitch, -5f, 88f); _tDist = Mathf.Clamp(distance, minDistance, maxDistance);
            if (instant) { _pivot = _tPivot; _yaw = _tYaw; _pitch = _tPitch; _dist = _tDist; Apply(); }
        }

        /// <summary>Focus a world position (e.g. a selected region) keeping the current viewing direction.</summary>
        public void Focus(Vector3 worldPos, float distance)
        {
            if (_roam) SetFreeRoam(false);
            Set(worldPos, _tYaw, Mathf.Max(_tPitch, 25f), distance);
        }

        public void Orbit(Vector2 deltaPixels)
        {
            _tYaw += deltaPixels.x * orbitSpeed;
            _tPitch = Mathf.Clamp(_tPitch - deltaPixels.y * orbitSpeed, -5f, 88f);
        }

        public void Pan(Vector2 deltaPixels)
        {
            if (cam == null) return;
            var k = panSpeed * _tDist;
            _tPivot += (-cam.transform.right * deltaPixels.x - cam.transform.up * deltaPixels.y) * k;
        }

        public void Zoom(float notches) => _tDist = Mathf.Clamp(_tDist * Mathf.Pow(1f - zoomSpeed, notches), minDistance, maxDistance);

        // ------------------------------------------------------------------ free roam

        public void SetFreeRoam(bool on)
        {
            if (on == _roam || cam == null) return;
            _roam = on;
            if (on)
            {
                _roamPos = cam.transform.position;
                var e = cam.transform.rotation.eulerAngles;
                _roamYaw = e.y;
                _roamPitch = e.x > 180f ? e.x - 360f : e.x;
            }
            else
            {
                // hand back to orbit: pivot 2 m in front of the camera, same view direction
                var rot = Quaternion.Euler(_roamPitch, _roamYaw, 0f);
                var pivot = _roamPos + rot * Vector3.forward * 2f;
                _pivot = _tPivot = pivot;
                _yaw = _tYaw = _roamYaw;
                _pitch = _tPitch = Mathf.Clamp(_roamPitch, -5f, 88f);
                _dist = _tDist = 2f;
                _pivotVel = Vector3.zero;
            }
            FreeRoamChanged?.Invoke(on);
        }

        /// <summary>Free-roam step: move = (right, up, forward) in -1..1, look = mouse delta in pixels.</summary>
        public void Roam(Vector3 move, Vector2 look, bool fast, float dt)
        {
            if (!_roam) return;
            _roamYaw += look.x * lookSensitivity;
            _roamPitch = Mathf.Clamp(_roamPitch - look.y * lookSensitivity, -85f, 85f);
            var rot = Quaternion.Euler(0f, _roamYaw, 0f);
            var v = rot * new Vector3(move.x, 0f, move.z) + Vector3.up * move.y;
            if (v.sqrMagnitude > 1f) v.Normalize();
            _roamPos += v * (roamSpeed * (fast ? roamFastMultiplier : 1f) * dt);
            _roamPos = Constrain(_roamPos, true);
        }

        private Vector3 Constrain(Vector3 p, bool keepOut)
        {
            double x = p.x, y = p.y, z = p.z;
            NavBounds.Resolve(ref x, ref y, ref z, collisionRadius, _room, keepOut ? _keepOut : null);
            return new Vector3((float)x, (float)y, (float)z);
        }

        // ------------------------------------------------------------------ stage composition

        /// <summary>Free stage rectangle in screen pixels (origin bottom-left). Called by NeramApp every frame.</summary>
        public void SetStage(Rect screenPx)
        {
            _stagePx = screenPx;
            _hasStage = screenPx.width > 32 && screenPx.height > 32;
        }

        public void ClearStage() => _hasStage = false;

        private void LateUpdate()
        {
            float dt = Time.unscaledDeltaTime;
            if (_roam)
            {
                if (cam != null)
                {
                    cam.transform.position = _roamPos;
                    cam.transform.rotation = Quaternion.Euler(_roamPitch, _roamYaw, 0f);
                }
            }
            else
            {
                _pivot = Vector3.SmoothDamp(_pivot, _tPivot, ref _pivotVel, smoothTime, Mathf.Infinity, dt);
                _yaw = Mathf.SmoothDampAngle(_yaw, _tYaw, ref _yawVel, smoothTime, Mathf.Infinity, dt);
                _pitch = Mathf.SmoothDamp(_pitch, _tPitch, ref _pitchVel, smoothTime, Mathf.Infinity, dt);
                _dist = Mathf.SmoothDamp(_dist, _tDist, ref _distVel, smoothTime, Mathf.Infinity, dt);
                Apply();
            }
            ApplyComposition(dt);
        }

        private void Apply()
        {
            if (cam == null) return;
            var rot = Quaternion.Euler(_pitch, _yaw, 0f);
            // orbit camera stays inside the room (it may come close to the patient for inspection)
            cam.transform.position = Constrain(_pivot + rot * new Vector3(0, 0, -_dist), false);
            cam.transform.rotation = rot;
        }

        private void ApplyComposition(float dt)
        {
            if (cam == null) return;
            Vector2 target = Vector2.zero;
            if (composeToStage && _hasStage && Screen.width > 0 && Screen.height > 0)
            {
                target = new Vector2(_stagePx.center.x / Screen.width * 2f - 1f, _stagePx.center.y / Screen.height * 2f - 1f);
                target.x = Mathf.Clamp(target.x, -0.6f, 0.6f);
                target.y = Mathf.Clamp(target.y, -0.6f, 0.6f);
            }
            _shift = Vector2.SmoothDamp(_shift, target, ref _shiftVel, 0.2f, Mathf.Infinity, dt);
            cam.ResetProjectionMatrix();
            if (_shift.sqrMagnitude < 1e-8f) return;
            var p = cam.projectionMatrix;
            // ndc.x = m00*x/(-z) - m02  ->  m02 = -shift moves the image centre to +shift in NDC.
            p.m02 = -_shift.x;
            p.m12 = -_shift.y;
            cam.projectionMatrix = p;
        }
    }
}
