#!/usr/bin/env python3
"""Generate the JSON Schema and the C# field table from unity/schema/replay_fields.json.

replay_fields.json is the single source of truth for replay field names, groups, types,
nullability, units and ranges. Run this script after editing it:

    python tools/gen_replay_schema.py          # writes both outputs
    python tools/gen_replay_schema.py --check  # exits 1 if outputs are stale (used by tests/CI)

Outputs
  unity/schema/replay_schema.json               JSON Schema (draft 2020-12), structural rules only
  unity_editor/Assets/Scripts/Core/ReplayFields.g.cs   C# field table compiled into Neram.Core

Semantic rules (cross-field consistency, ordering, cohort, source tags) are not expressible
in JSON Schema; they live in unity/schema/VALIDATION_RULES.md and are implemented identically
in ReplayValidator.cs (Unity) and integration/validate_replay.py (Python).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "unity" / "schema" / "replay_fields.json"
OUT_SCHEMA = ROOT / "unity" / "schema" / "replay_schema.json"
OUT_CS = ROOT / "unity_editor" / "Assets" / "Scripts" / "Core" / "ReplayFields.g.cs"


def json_type(field):
    k = field["kind"]
    if k == "number":
        t = {"type": ["number", "null"] if field["nullable"] else "number"}
        if field.get("range_mode") == "error":
            if field.get("min") is not None:
                t["minimum"] = field["min"]
            if field.get("max") is not None:
                t["maximum"] = field["max"]
        return t
    if k == "bool":
        return {"type": ["boolean", "null"] if field["nullable"] else "boolean"}
    if k in ("int", "enum"):
        t = {"type": ["integer", "null"] if field["nullable"] else "integer"}
        if field.get("min") is not None:
            t["minimum"] = field["min"]
        if field.get("max") is not None:
            t["maximum"] = field["max"]
        return t
    if k in ("string", "string_enum"):
        return {"type": ["string", "null"] if field["nullable"] else "string"}
    raise ValueError(f"unknown kind {k}")


def build_schema(doc):
    groups = {}
    for g in doc["groups"]:
        fields = [f for f in doc["fields"] if f["group"] == g]
        props = {f["name"]: json_type(f) for f in fields}
        if g == "src":
            for f in fields:
                props[f["name"]] = {"enum": doc["src_allowed"][f["name"]]}
        required = [f["name"] for f in fields if not f.get("optional")]
        groups[g] = {"type": "object", "properties": props, "required": required, "additionalProperties": False}
    header = doc["header"]
    hprops = {
        "type": {"const": "header"},
        "schema_version": {"enum": doc["supported_schema_versions"]},
        "scenario_id": {"type": "string", "minLength": 1},
        "created_utc": {"type": "string"},
        "params_version": {"type": "string"},
        "spec_version": {"type": "string"},
        "inputs": {"type": "object", "additionalProperties": {"type": "string"}},
        "disclaimer": {"type": "string", "minLength": 1},
        "cohort": {"enum": header["cohort_allowed"]},
        "static_context": {"type": ["object", "null"]},
        "placeholder": {"type": "boolean"},
        "generator": {"type": "string"},
        "scenario_info": {"type": "object"},
        "params_used": {"type": "object"},
    }
    frame = {
        "type": "object",
        "properties": dict({"type": {"const": "frame"}}, **groups),
        "required": ["type"] + doc["groups"],
        "additionalProperties": False,
    }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://neram.local/schema/replay/1.0",
        "title": "NERAM replay (JSONL): line 1 = header object, lines 2..N = frame objects",
        "description": "GENERATED by tools/gen_replay_schema.py from unity/schema/replay_fields.json. Do not edit by hand. "
                       "Structural rules only; semantic rules: unity/schema/VALIDATION_RULES.md.",
        "$defs": {
            "header": {"type": "object", "properties": hprops,
                       "required": list(header["required"].keys()), "additionalProperties": False},
            "frame": frame,
        },
        "oneOf": [{"$ref": "#/$defs/header"}, {"$ref": "#/$defs/frame"}],
    }


def cs_str(s):
    return "null" if s is None else '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def cs_num(x):
    return "double.NaN" if x is None else repr(float(x))


def build_cs(doc):
    kinds = {"number": "FieldKind.Number", "bool": "FieldKind.Bool", "int": "FieldKind.Int", "enum": "FieldKind.Enum",
             "string": "FieldKind.String", "string_enum": "FieldKind.StringEnum"}
    modes = {"none": "RangeMode.None", "error": "RangeMode.Error", "warn": "RangeMode.Warn"}
    lines = []
    for i, f in enumerate(doc["fields"]):
        lines.append(
            f"            new FieldDef({i}, {cs_str(f['group'])}, {cs_str(f['name'])}, {kinds[f['kind']]}, "
            f"{str(f['nullable']).lower()}, {cs_str(f['unit'])}, {cs_num(f.get('min'))}, {cs_num(f.get('max'))}, "
            f"{modes[f['range_mode']]}, {f['decimals']}, {str(bool(f.get('optional'))).lower()}, {cs_str(f.get('enum'))}, "
            f"{cs_str(f.get('label'))}, {str(bool(f.get('proposed'))).lower()}),")
    src_allowed = []
    for g, tags in doc["src_allowed"].items():
        src_allowed.append(f'            {{ "{g}", new[] {{ ' + ", ".join(f'"{t}"' for t in tags) + " } },")
    groups = ", ".join(f'"{g}"' for g in doc["groups"])
    versions = ", ".join(f'"{v}"' for v in doc["supported_schema_versions"])
    cohorts = ", ".join(f'"{c}"' for c in doc["header"]["cohort_allowed"])
    return f"""// <auto-generated>
// GENERATED by tools/gen_replay_schema.py from unity/schema/replay_fields.json.
// Do not edit by hand: edit replay_fields.json and re-run the generator.
// </auto-generated>
using System.Collections.Generic;

namespace Neram.Core
{{
    public static partial class ReplayFields
    {{
        public const string SchemaSourceVersion = "{doc['replay_schema_version']}";
        public static readonly string[] SupportedSchemaVersions = {{ {versions} }};
        public static readonly string[] Groups = {{ {groups} }};
        public static readonly string[] AllowedCohorts = {{ {cohorts} }};

        public static readonly Dictionary<string, string[]> AllowedSourceTags = new Dictionary<string, string[]>
        {{
{chr(10).join(src_allowed)}
        }};

        public static readonly FieldDef[] All =
        {{
{chr(10).join(lines)}
        }};
    }}
}}
"""


def main():
    doc = json.loads(SRC.read_text())
    schema = json.dumps(build_schema(doc), indent=1) + "\n"
    cs = build_cs(doc)
    if "--check" in sys.argv:
        stale = []
        if not OUT_SCHEMA.exists() or OUT_SCHEMA.read_text() != schema:
            stale.append(str(OUT_SCHEMA))
        if not OUT_CS.exists() or OUT_CS.read_text() != cs:
            stale.append(str(OUT_CS))
        if stale:
            print("STALE generated files (run tools/gen_replay_schema.py):", *stale, sep="\n  ")
            sys.exit(1)
        print("generated schema files are up to date")
        return
    OUT_SCHEMA.write_text(schema)
    OUT_CS.write_text(cs)
    print("wrote", OUT_SCHEMA.relative_to(ROOT), "and", OUT_CS.relative_to(ROOT))


if __name__ == "__main__":
    main()
